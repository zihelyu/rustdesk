#!/usr/bin/env python3
"""Generate branding and configured host defaults for the build checkout."""

import argparse
import base64
from xml.sax.saxutils import escape
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit


def load_brand(root):
    data = json.loads((root / "custom/branding.json").read_text(encoding="utf-8"))
    for key in ("display_name", "company_name", "website", "privacy_url",
                "permanent_password", "rendezvous_server", "server_public_key", "api_server", "update_origin",
                "download_url", "update_public_key"):
        value = data.get(key)
        if not isinstance(value, str) or not value or any(ord(c) < 32 for c in value):
            raise ValueError(f"{key}: expected nonempty text without control characters")
    # These strings also become file names and values in privileged CMD scripts.
    for key in ("display_name", "company_name"):
        if any(c in data[key] for c in '<>:"/\\|?*%&^!'):
            raise ValueError(f"{key}: contains a Windows file-name or CMD metacharacter")
        if data[key].endswith((" ", ".")):
            raise ValueError(f"{key}: cannot end with a space or dot")
    for key in ("website", "privacy_url", "api_server", "update_origin", "download_url"):
        url = urlsplit(data[key])
        if url.scheme not in ("http", "https") or not url.hostname:
            raise ValueError(f"{key}: expected an http(s) URL")
    if type(data.get("copyright_year")) is not int or not 2000 <= data["copyright_year"] <= 9999:
        raise ValueError("copyright_year: expected a four-digit year")
    if len(data["permanent_password"]) < 6:
        raise ValueError("permanent_password: expected at least six characters")
    origin = urlsplit(data["update_origin"])
    if (origin.scheme != "https" or origin.path or origin.query or origin.fragment
            or origin.username or origin.password or origin.port
            or data["update_origin"] != "https://" + origin.hostname):
        raise ValueError("update_origin: expected canonical HTTPS origin without port/path")
    key = base64.b64decode(data["update_public_key"], validate=True)
    if len(key) != 32 or base64.b64encode(key).decode() != data["update_public_key"]:
        raise ValueError("update_public_key: expected canonical base64 32-byte Ed25519 key")
    return data


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def dart_quoted(value):
    return quoted(value).replace("$", "\\$")


def cpp_wide(value):
    result = []
    for char in value:
        point = ord(char)
        if point > 0xFFFF:
            result.append(f"\\U{point:08x}")
        elif point > 0x7F:
            result.append(f"\\u{point:04x}")
        elif char in ('"', "\\"):
            result.append("\\" + char)
        else:
            result.append(char)
    return 'L"' + "".join(result) + '"'


def replace_field(text, pattern, replacement, label):
    result, count = re.subn(pattern, lambda _: replacement, text, flags=re.MULTILINE)
    if count != 1:
        raise ValueError(f"{label}: expected exactly one resource field, found {count}")
    return result


def render(root, data):
    name = data["display_name"]
    company = data["company_name"]
    copyright_text = f'Copyright © {data["copyright_year"]} {company}. All rights reserved.'
    notice = "// Generated by custom/apply_branding.py; edit custom/branding.json instead.\n"
    public_key = list(base64.b64decode(data["update_public_key"]))
    outputs = {
        "src/branding.rs": notice
        + f"pub const DISPLAY_NAME: &str = {quoted(name)};\n"
        + f"pub const COMPANY_NAME: &str = {quoted(company)};\n"
        + f"pub const PERMANENT_PASSWORD: &str = {quoted(data['permanent_password'])};\n"
        + f"pub const API_SERVER: &str = {quoted(data['api_server'])};\n"
        + f"pub const UPDATE_ORIGIN: &str = {quoted(data['update_origin'])};\n"
        + f"pub const DOWNLOAD_URL: &str = {quoted(data['download_url'])};\n"
        + f"pub const UPDATE_PUBLIC_KEY: [u8; 32] = {public_key};\n",
        "flutter/lib/branding.dart": notice
        + f"const String brandDisplayName = {dart_quoted(name)};\n"
        + f"const String brandCompanyName = {dart_quoted(company)};\n"
        + f"const String brandWebsite = {dart_quoted(data['website'])};\n"
        + f"const String brandPrivacyUrl = {dart_quoted(data['privacy_url'])};\n"
        + f"const String brandUpdateOrigin = {dart_quoted(data['update_origin'])};\n"
        + f"const String brandDownloadUrl = {dart_quoted(data['download_url'])};\n",
        "flutter/windows/runner/branding.h": notice
        + "#pragma once\n"
        + f"inline constexpr wchar_t kBrandDisplayName[] = {cpp_wide(name)};\n",
    }
    resource = root / "flutter/windows/runner/Runner.rc"
    text = resource.read_text(encoding="utf-8")
    fields = {
        "CompanyName": company,
        "FileDescription": name,
        "InternalName": "rustdesk",
        "LegalCopyright": copyright_text,
        "OriginalFilename": "rustdesk.exe",
        "ProductName": name,
    }
    for key, value in fields.items():
        text = replace_field(
            text, rf'^[ \t]*VALUE "{key}",[^\n]*$',
            f'            VALUE "{key}", {quoted(value)} "\\0"', f"Runner.rc:{key}",
        )
    outputs["flutter/windows/runner/Runner.rc"] = text
    for filename in ("Cargo.toml", "libs/portable/Cargo.toml"):
        text = (root / filename).read_text(encoding="utf-8")
        if filename == "libs/portable/Cargo.toml":
            text = replace_field(text, r'^description\s*=.*$',
                                 f'description = {quoted(name)}', f"{filename}:description")
        pattern = r'(?ms)^\[package\.metadata\.winres\]\n(.*?)(?=^\[|\Z)'
        section = re.search(pattern, text)
        if section is None:
            raise ValueError(f"{filename}: missing package.metadata.winres")
        body = section[1]
        for key, value in {
            "LegalCopyright": copyright_text,
            "ProductName": name,
            "OriginalFilename": "rustdesk.exe",
            "FileDescription": name,
        }.items():
            body = replace_field(body, rf'^{key}\s*=.*$', f'{key} = {quoted(value)}', f"{filename}:{key}")
        company_field = f'CompanyName = {quoted(company)}'
        if re.search(r'^CompanyName\s*=', body, re.MULTILINE):
            body = replace_field(body, r'^CompanyName\s*=.*$', company_field, f"{filename}:CompanyName")
        else:
            body = company_field + "\n" + body
        outputs[filename] = text[:section.start(1)] + body + text[section.end(1):]
    filename = "libs/hbb_common/src/config.rs"
    text = (root / filename).read_text(encoding="utf-8")
    text = replace_field(
        text, r'^pub const RENDEZVOUS_SERVERS:.*$',
        f"pub const RENDEZVOUS_SERVERS: &[&str] = &[{quoted(data['rendezvous_server'])}];",
        f"{filename}:RENDEZVOUS_SERVERS",
    )
    text = replace_field(
        text, r'^pub const RS_PUB_KEY:.*$',
        f"pub const RS_PUB_KEY: &str = {quoted(data['server_public_key'])};",
        f"{filename}:RS_PUB_KEY",
    )
    outputs[filename] = text
    filename = "flutter/android/app/src/main/AndroidManifest.xml"
    text = (root / filename).read_text(encoding="utf-8")
    text, count = re.subn(r'android:label="[^"]*"', lambda _: 'android:label="' + escape(name, {'"': '&quot;'}) + '"', text)
    if count != 2:
        raise ValueError("Android manifest: expected application and input-service labels")
    outputs[filename] = text
    filename = "flutter/android/app/src/main/res/values/strings.xml"
    text = (root / filename).read_text(encoding="utf-8")
    text = replace_field(text, r'^[ \t]*<string name="app_name">.*</string>$',
                         '    <string name="app_name">' + escape(name) + '</string>', filename)
    outputs[filename] = text
    for filename in ("res/rustdesk.desktop", "res/rustdesk-link.desktop"):
        text = (root / filename).read_text(encoding="utf-8")
        text, count = re.subn(r'^Name=.*$', lambda _: "Name=" + name, text, count=1, flags=re.M)
        if count != 1:
            raise ValueError(filename + ": missing desktop name")
        outputs[filename] = text
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check without changing any files")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    try:
        outputs = {name: text.encode("utf-8") for name, text in render(root, load_brand(root)).items()}
        ico = (root / "custom/icons/icon.ico").read_bytes()
        svg = (root / "custom/icons/icon.svg").read_bytes()
        for name in ("flutter/windows/runner/resources/app_icon.ico", "res/icon.ico",
                     "res/tray-icon.ico", "flutter/assets/icon.ico"):
            outputs[name] = ico
        outputs["flutter/assets/icon.svg"] = svg
        outputs["res/scalable.svg"] = svg
        outputs["res/icon.png"] = (root / "custom/icons/icon-512.png").read_bytes()
        outputs["res/128x128@2x.png"] = (root / "custom/icons/icon-256.png").read_bytes()
        for density, size in (("mdpi",48),("hdpi",72),("xhdpi",96),("xxhdpi",144),("xxxhdpi",192)):
            png = (root / f"custom/icons/icon-{size}.png").read_bytes()
            for name in ("ic_launcher", "ic_launcher_round", "ic_launcher_foreground"):
                outputs[f"flutter/android/app/src/main/res/mipmap-{density}/{name}.png"] = png
    except (OSError, ValueError) as error:
        print(f"Branding: {error}", file=sys.stderr)
        return 1
    changed = []
    for filename, data in outputs.items():
        path = root / filename
        if not path.exists() or path.read_bytes() != data:
            changed.append(filename)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if args.check and changed:
        print("Branding is stale: " + ", ".join(changed), file=sys.stderr)
        return 1
    print("Branding is current." if args.check else f"Branding applied: {len(changed)} file(s) updated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
